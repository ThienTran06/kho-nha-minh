CREATE TABLE app_auth (
  id BIGINT PRIMARY KEY,
  password_hash VARCHAR(255),
  initialized BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL
);
INSERT INTO app_auth(id, password_hash, initialized, created_at, updated_at)
VALUES (1, NULL, FALSE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(80) UNIQUE,
  name VARCHAR(180) NOT NULL,
  unit VARCHAR(60) NOT NULL,
  quantity DECIMAL(19,3) NOT NULL DEFAULT 0,
  min_stock DECIMAL(19,3) NOT NULL DEFAULT 0,
  unit_price DECIMAL(19,2) NOT NULL DEFAULT 0,
  note VARCHAR(500),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_products_name ON products(name);
CREATE INDEX idx_products_quantity ON products(quantity);

CREATE TABLE inventory_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  type VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  product_id BIGINT NOT NULL,
  product_name_snapshot VARCHAR(180) NOT NULL,
  unit_snapshot VARCHAR(60) NOT NULL,
  quantity DECIMAL(19,3) NOT NULL,
  unit_cost DECIMAL(19,2),
  note VARCHAR(500),
  created_at TIMESTAMP(6) NOT NULL,
  voided_at TIMESTAMP(6),
  CONSTRAINT fk_tx_product FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE INDEX idx_tx_created ON inventory_transactions(created_at);
CREATE INDEX idx_tx_product ON inventory_transactions(product_id);
CREATE INDEX idx_tx_type ON inventory_transactions(type);

CREATE TABLE expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_date DATE NOT NULL,
  category VARCHAR(100) NOT NULL,
  amount DECIMAL(19,2) NOT NULL,
  note VARCHAR(500),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_expense_date ON expenses(expense_date);
