ALTER TABLE app_auth ADD COLUMN recovery_hash VARCHAR(255);
ALTER TABLE products ADD COLUMN target_stock DECIMAL(19,3) NOT NULL DEFAULT 0;

CREATE TABLE stocktakes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  product_name_snapshot VARCHAR(180) NOT NULL,
  unit_snapshot VARCHAR(60) NOT NULL,
  system_quantity DECIMAL(19,3) NOT NULL,
  actual_quantity DECIMAL(19,3) NOT NULL,
  difference_quantity DECIMAL(19,3) NOT NULL,
  note VARCHAR(500),
  counted_at TIMESTAMP(6) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_stocktake_product FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE INDEX idx_stocktake_product ON stocktakes(product_id);
CREATE INDEX idx_stocktake_counted ON stocktakes(counted_at);

CREATE TABLE audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action VARCHAR(60) NOT NULL,
  entity_type VARCHAR(60),
  entity_id BIGINT,
  description VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_audit_created ON audit_events(created_at);
